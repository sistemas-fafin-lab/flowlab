-- ═══════════════════════════════════════════════════════════════════════════════
-- Auditoria e limite de chamadas das integrações server-to-server
--
-- Primeiro consumidor: o LAB-BRAIN, que consulta as tabelas do Envio ao Álvaro
-- (ac_apoio_*) por api/integracoes/lab-brain-apoio-*. Cada chamada autorizada
-- vira uma linha aqui; a mesma tabela serve de janela deslizante do limite por
-- minuto (a função abaixo conta e grava na mesma transação, sob lock).
--
-- Só o backend (service role) lê e grava: RLS ligada e sem policy. Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS integracao_chamadas (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  integracao  text NOT NULL,                       -- ex.: 'lab-brain'
  rota        text NOT NULL,                       -- ex.: 'lab-brain-apoio-requisicao'
  parametros  jsonb NOT NULL DEFAULT '{}'::jsonb,  -- o que foi consultado (cod, filtros)
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_integracao_chamadas_integracao_created
  ON integracao_chamadas(integracao, created_at DESC);

ALTER TABLE integracao_chamadas ENABLE ROW LEVEL SECURITY;

-- Conta as chamadas da integração na janela e, se ainda houver cota, grava esta.
-- Sem cota: não grava e devolve em quantos segundos a chamada mais antiga sai da
-- janela (vira o header Retry-After). O advisory lock serializa chamadas
-- simultâneas da mesma integração, para duas não passarem pela última vaga.
CREATE OR REPLACE FUNCTION integracao_registrar_chamada(
  p_integracao      text,
  p_rota            text,
  p_parametros      jsonb,
  p_limite          integer,
  p_janela_segundos integer
)
RETURNS TABLE (permitido boolean, retry_after integer)
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_total       integer;
  v_mais_antiga timestamptz;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('integracao_chamadas:' || p_integracao));

  SELECT count(*), min(c.created_at)
    INTO v_total, v_mais_antiga
    FROM integracao_chamadas c
   WHERE c.integracao = p_integracao
     AND c.created_at > now() - make_interval(secs => p_janela_segundos);

  IF v_total >= p_limite THEN
    RETURN QUERY SELECT
      false,
      GREATEST(1, CEIL(EXTRACT(EPOCH FROM
        (v_mais_antiga + make_interval(secs => p_janela_segundos) - now())))::integer);
    RETURN;
  END IF;

  INSERT INTO integracao_chamadas (integracao, rota, parametros)
  VALUES (p_integracao, p_rota, COALESCE(p_parametros, '{}'::jsonb));

  RETURN QUERY SELECT true, 0;
END;
$$;

REVOKE ALL ON FUNCTION integracao_registrar_chamada(text, text, jsonb, integer, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION integracao_registrar_chamada(text, text, jsonb, integer, integer)
  TO service_role;
