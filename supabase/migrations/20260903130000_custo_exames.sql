  END IF;
END $$;

-- ═══════════════════════════════════════════════════════════════════════════════
-- 1. TABELA
-- ═══════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.custo_exames (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo                TEXT NOT NULL DEFAULT '',
  tuss                  TEXT NOT NULL DEFAULT '',
  nome                  TEXT NOT NULL CHECK (btrim(nome) <> ''),
  local                 TEXT NOT NULL DEFAULT '',
  custo_direto          NUMERIC(12,2) NOT NULL DEFAULT 0,
  custo_indireto        NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Composição do custo indireto (rateio de pessoal, depreciação, ...), livre —
  -- é o IndirectComposer da tela quem dá forma a cada item ({id,label,value}).
  custo_indireto_itens  JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.custo_exames IS 'Catálogo de exames do módulo Controle de Custos: custo direto/indireto usado para cruzar com o valor cobrado por fonte pagadora. custo_total é calculado (direto + indireto), não é coluna.';
COMMENT ON COLUMN public.custo_exames.codigo IS 'Mnemônico interno do exame. Pode ser vazio (a planilha de origem não tinha mnemônico para ~1/3 dos exames).';
COMMENT ON COLUMN public.custo_exames.tuss IS 'Código TUSS. Pode ser vazio (procedimentos sem TUSS cadastrado na planilha de origem).';

CREATE INDEX IF NOT EXISTS idx_custo_exames_nome ON public.custo_exames (nome);

CREATE OR REPLACE FUNCTION public.custo_exames_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_custo_exames_updated_at ON public.custo_exames;
CREATE TRIGGER trigger_custo_exames_updated_at
  BEFORE UPDATE ON public.custo_exames
  FOR EACH ROW EXECUTE FUNCTION public.custo_exames_set_updated_at();

