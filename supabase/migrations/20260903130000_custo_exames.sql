-- Controle de Custos — catálogo de exames (custo direto/indireto)
-- Migration: 20260903130000_custo_exames.sql
--
-- A tela /cost-control (aba "Exames") vivia inteiramente em memória
-- (SEED_EXAMS em src/hooks/useCostControl.ts): qualquer cadastro, edição ou
-- exclusão feita na tela sumia ao recarregar a página. Esta migration cria a
-- tabela que passa a sustentar aquela tela, e semeia o catálogo real (503
-- exames) recebido do setor — planilha "Tabela Comparativo de Valores A C -
-- Orçamento Particular", convertendo:
--
--   Mnemônico        → codigo
--   Código TUSS      → tuss
--   Descrição Exame  → nome
--   Custo alvaro     → custo_direto
--   (sem correspondência na planilha) → local, custo_indireto ficam vazios/0
--
-- custo_total NÃO é coluna: continua calculado (custo_direto + custo_indireto)
-- pela tela, como já era com o seed em memória — evita o total divergir da
-- soma se um dos dois for editado sem o outro.
--
-- Fontes Pagadoras (aba ao lado) fica de fora de propósito: a tela já rotula
-- aqueles dados como "somente leitura — espelhados do APLIS" e são só um mock
-- de exemplo hoje, sem pedido do usuário para persistir.
--
-- Mesmo padrão de public.fat_views_salvas (20260810160000): CRUD simples de
-- linha própria sob RLS, sem RPC. Reaproveita canViewBilling/canManageBilling
-- — já são o gate da rota /cost-control em App.tsx, sem permissão nova.
-- ═══════════════════════════════════════════════════════════════════════════════

