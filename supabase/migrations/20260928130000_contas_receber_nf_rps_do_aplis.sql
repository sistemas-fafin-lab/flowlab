-- 2) Número da nota no título
-- ----------------------------------------------------------------------------
UPDATE notas n
   SET numero_nota = x.nfe,
       updated_at  = NOW()
  FROM (
    SELECT nl.id_nota, MIN(l.nfe_numero) AS nfe
      FROM nota_lote nl
      JOIN lotes l ON l.id_lote = nl.id_lote
     WHERE nl.id_nota IN (SELECT nl2.id_nota FROM nota_lote nl2 JOIN lotes l2 ON l2.id_lote = nl2.id_lote
                           WHERE l2.aplis_id IN (SELECT aplis_id FROM _nf_rps))
     GROUP BY nl.id_nota
    HAVING COUNT(*) = COUNT(l.nfe_numero) AND COUNT(DISTINCT l.nfe_numero) = 1
  ) x
 WHERE n.id_nota = x.id_nota
   AND NULLIF(TRIM(n.numero_nota), '') IS NULL;

