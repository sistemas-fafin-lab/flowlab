DO $$
DECLARE v_faltando TEXT;
BEGIN
  SELECT string_agg(t.aplis_id, ', ' ORDER BY t.aplis_id) INTO v_faltando
    FROM _nf_rps t LEFT JOIN lotes l ON l.aplis_id = t.aplis_id
   WHERE l.id_lote IS NULL;
  IF v_faltando IS NOT NULL THEN
    RAISE EXCEPTION 'Lote(s) não encontrado(s) em lotes: %', v_faltando;
  END IF;
END $$;

UPDATE lotes l
   SET nfe_numero          = COALESCE(l.nfe_numero, t.nfe_numero),
       numero_rps          = COALESCE(l.numero_rps, t.numero_rps),
       data_vencimento_rps = COALESCE(l.data_vencimento_rps, t.data_vencimento_rps),
       updated_at          = NOW()
  FROM _nf_rps t
 WHERE l.aplis_id = t.aplis_id
   AND (l.nfe_numero IS NULL OR l.numero_rps IS NULL OR l.data_vencimento_rps IS NULL);

